"""Run against a dedicated empty instance, e.g. PORT=3200 STORAGE_DIR=/tmp/album-ui-test npm start."""
import os
import time
import subprocess
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
base = os.environ.get("TEST_URL", "http://127.0.0.1:3200")
screens = Path(os.environ.get("SCREENSHOT_DIR", "/workspace/scratch/album-screens"))
screens.mkdir(exist_ok=True)
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path="/usr/bin/chromium")
    page = browser.new_page(viewport={"width":1280,"height":720})
    errors=[]
    page.on("pageerror",lambda e:errors.append(str(e)))
    page.goto(base)
    expect(page.locator("h1")).to_contain_text("Сохраняйте")
    for route in ["", "albums", "people", "places", "tags", "settings", "trash"]:
        page.goto(base+"/"+route)
        page.wait_for_timeout(400)
        page.screenshot(path=str(screens/(route or "home"))+".png")
        assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), route
    page.get_by_role("button",name="Создать свой семейный архив").click()
    dialog=page.locator("dialog")
    dialog.get_by_label("Ваше имя").fill("Проверочная семья")
    dialog.get_by_label("Email",exact=True).fill("browser-"+str(time.time_ns())+"@example.test")
    dialog.get_by_label("Пароль",exact=True).fill("browser-testing-password")
    dialog.get_by_role("button",name="Создать аккаунт",exact=True).click()
    expect(page.locator("dialog")).to_have_count(0)
    page.goto(base+"/albums")
    page.get_by_role("button",name="Создать альбом",exact=True).click()
    dialog=page.locator("dialog")
    dialog.get_by_label("Название",exact=True).fill("Наши выходные")
    dialog.get_by_label("Описание",exact=True).fill("Проверка постоянного хранения")
    dialog.get_by_role("button",name="Сохранить",exact=True).click()
    expect(page.locator(".entity-card")).to_contain_text("Наши выходные")
    page.locator(".upload-top").click()
    dialog=page.locator("dialog")
    dialog.locator('input[type=file]').set_input_files(["public/assets/1.jpg","public/assets/2.jpg"])
    dialog.get_by_label("Альбом",exact=True).select_option(label="Наши выходные")
    page.screenshot(path=str(screens/"upload.png"))
    dialog.get_by_role("button",name="Загрузить",exact=True).click()
    expect(dialog.get_by_text("Сохранено",exact=True)).to_have_count(2,timeout=15000)
    dialog.get_by_role("button",name="Готово",exact=True).click()
    page.locator(".entity-card a").click()
    expect(page.locator(".photo-card")).to_have_count(2)
    page.locator(".photo-open").first.click()
    dialog=page.locator("dialog")
    dialog.get_by_role("button",name="В избранное",exact=True).click()
    expect(dialog.get_by_role("button",name="В избранное",exact=True)).to_have_attribute("aria-pressed","true")
    page.keyboard.press("ArrowRight")
    expect(page.locator(".viewer-media img")).to_be_visible()
    page.keyboard.press("Escape")
    for route,label in [("people","Добавить человека"),("places","Добавить место"),("tags","Создать тег")]:
        page.goto(base+"/"+route)
        page.get_by_role("button",name=label,exact=True).click()
        dialog=page.locator("dialog")
        dialog.get_by_label("Название",exact=True).fill("Проверка "+route)
        if route=="places":
            dialog.get_by_label("Широта",exact=True).fill("55.75")
            dialog.get_by_label("Долгота",exact=True).fill("37.61")
        dialog.get_by_role("button",name="Сохранить",exact=True).click()
        expect(page.locator(".entity-card")).to_have_count(1)
        if route=="places":
            expect(page.locator(".place-marker")).to_have_count(1)
    page.goto(base+"/photos")
    page.locator(".photo-open").first.click()
    dialog=page.locator("dialog")
    for label in ["Люди","Места","Теги"]:
        dialog.get_by_label(label,exact=True).select_option(index=0)
    dialog.get_by_role("button",name="Сохранить",exact=True).click()
    expect(page.locator(".toast")).to_contain_text("Изменения сохранены")
    page.keyboard.press("Escape")
    page.locator(".photo-open").first.click()
    page.locator("dialog").get_by_role("button",name="В корзину",exact=True).click()
    expect(page.locator("dialog")).to_have_count(0)
    page.goto(base+"/trash")
    expect(page.locator(".photo-card")).to_have_count(1)
    page.get_by_role("button",name="Выбрать все",exact=True).click()
    page.get_by_role("button",name="Восстановить",exact=True).click()
    expect(page.locator(".photo-card")).to_have_count(0)
    page.goto(base+"/settings")
    page.get_by_role("button",name="Тёмная тема",exact=False).click()
    page.get_by_role("button",name="Сохранить изменения",exact=True).click()
    expect(page.locator(".toast")).to_contain_text("Настройки сохранены")
    page.reload()
    expect(page.locator("html")).to_have_attribute("data-theme","dark")
    page.screenshot(path=str(screens/"settings-dark.png"))
    page.get_by_role("button",name="Светлая тема",exact=False).click()
    page.get_by_role("button",name="Сохранить изменения",exact=True).click()
    expect(page.locator(".toast")).to_contain_text("Настройки сохранены")
    ffmpeg=subprocess.check_output(["node","-e","console.log(require('@ffmpeg-installer/ffmpeg').path)"],text=True).strip()
    videos=[]
    for extension,codec in [("mp4","libx264"),("webm","libvpx")]:
        fixture=screens/("sample."+extension)
        subprocess.run([ffmpeg,"-y","-f","lavfi","-i","color=c=purple:s=160x120:d=2","-c:v",codec,"-threads","1",str(fixture)],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
        videos.append(str(fixture))
    page.locator(".upload-top").click()
    dialog=page.locator("dialog")
    dialog.locator("input[type=file]").set_input_files(videos)
    dialog.get_by_role("button",name="Загрузить",exact=True).click()
    expect(dialog.get_by_text("Сохранено",exact=True)).to_have_count(2,timeout=30000)
    dialog.get_by_role("button",name="Готово",exact=True).click()
    page.goto(base+"/videos")
    expect(page.locator(".photo-card")).to_have_count(2)
    for index in [0,1]:
        page.locator(".photo-open").nth(index).click()
        page.wait_for_function("document.querySelector('.viewer-media video').readyState >= 2")
        page.wait_for_function("document.querySelector('.viewer-media video').currentTime > 0")
        page.keyboard.press("Escape")
    page.goto(base+"/settings")
    page.get_by_role("button",name="Изменить профиль",exact=True).click()
    dialog=page.locator("dialog")
    dialog.get_by_label("Имя и фамилия",exact=True).fill("Семья после обновления")
    dialog.get_by_label("Email",exact=True).fill("updated-"+str(time.time_ns())+"@example.test")
    dialog.get_by_label("Текущий пароль",exact=True).fill("browser-testing-password")
    dialog.get_by_label("Новый пароль",exact=True).fill("updated-testing-password")
    dialog.get_by_label("Повторите новый пароль",exact=True).fill("updated-testing-password")
    dialog.get_by_label("Загрузить новый аватар",exact=True).set_input_files("public/assets/1.jpg")
    dialog.get_by_role("button",name="Сохранить профиль",exact=True).click()
    expect(page.locator("dialog")).to_have_count(0)
    expect(page.locator(".profile-card")).to_contain_text("Семья после обновления")
    expect(page.locator(".profile-avatar img")).to_be_visible()
    for width,height in [(1920,1080),(1440,900),(1280,720),(1024,768),(768,1024),(390,844),(375,667)]:
        page.set_viewport_size({"width":width,"height":height})
        for route in ["", "albums", "people", "places", "tags", "settings", "trash"]:
            page.goto(base+"/"+route)
            page.wait_for_timeout(100)
            assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"), (route,width)
        if width==390:
            page.screenshot(path=str(screens/"mobile-settings.png"),full_page=True)
    assert not errors,errors
    print("PASS registration, albums, multi-upload, viewer, favorites, people/places/tags, linking, trash/restore, settings persistence, 7 responsive sizes")
    browser.close()
