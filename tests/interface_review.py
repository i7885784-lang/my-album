def bounds(page,selector):
    for rect in page.locator(selector).evaluate_all("(items)=>items.map(e=>{const r=e.getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom,w:r.width,h:r.height}})"):
        assert rect["x"]>=-1 and rect["right"]<=page.viewport_size["width"]+1,(selector,rect)
        assert rect["y"]>=-1 and rect["bottom"]<=page.viewport_size["height"]+1,(selector,rect)

